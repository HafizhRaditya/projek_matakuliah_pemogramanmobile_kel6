@Composable
fun WaktuKuTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Dynamic color (Android 12+) mengganti SEMUA warna dengan warna wallpaper
    // HP. Bawaannya sengaja false: kalau true, WaktuKu tampil berbeda di setiap
    // HP dan identitas warnanya hilang - itulah yang terjadi sebelum palet ini
    // dibuat. Parameternya tetap disediakan supaya kelak bisa dijadikan pilihan
    // "ikuti warna wallpaper" di layar Pengaturan.
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> darkScheme
        else -> lightScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}
